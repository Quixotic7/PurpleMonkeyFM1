"""PurpleMonkey's FM6 sounds, one per pet (firmware/src/pm_sound.c) -> a C header of packed 128-byte voices.

  tools/gen_pm_patches.py OUT.h

PurpleMonkey's own patches, written here as operator settings with gen_fm6_patches.py's helpers (no factory ROM
data of any instrument). Each is voiced for small hands and a small speaker: an instant attack that says "you
pressed a key", a mellow body (modulators that die away quickly, so a held or repeated note stays soft), nothing
harsh when eight sound at once. BRIGHT (PRESETS) moves the modulators' level around what is written here, LENGTH
(ALGORITHM) the envelopes' decay and release rates (pm_sound.c).
Algorithm 5 = three pairs (1<-2, 3<-4, 5<-6 with the feedback); 32 = six carriers.
"""
