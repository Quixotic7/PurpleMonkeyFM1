def main(path):
    L = ["/* generated by tools/gen_pm_patches.py: PurpleMonkey's FM6 voices (packed), in PM_MONKEY .. PM_LLAMA order */",
         "#pragma once", f"static const uint8_t PM_FM6[{len(PETS)}][128] = {{"]
    for name, v in PETS:
        L.append("    {" + ", ".join(str(x) for x in pack(v)) + f"}},   /* {name} */")
    L.append("};")
    Path(path).write_text("\n".join(L) + "\n")
    print(f"pm patches: {len(PETS)} -> {path}")


if __name__ == "__main__":
    main(sys.argv[1])
